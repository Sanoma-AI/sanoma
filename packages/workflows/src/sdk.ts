import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import type { CollectionEntry, ConfigDescription, OpEntry, WorkflowEntry } from "./describe.ts";
import { isObject } from "./resource.ts";
import { type CedarSchemaJson, SCHEMA_FILE, schemaText } from "./schema.ts";
import { apiNameOf, DATA_VENDOR, problemLine } from "./shared.ts";

// A company's generated SDK, `.sanoma/api.ts`: the types of a site's `api` from `sanoma/site`,
// written from `describeConfig` (types and JSDoc only: `api` itself is one generic client). It
// augments `sanoma/site`'s `Register`, so it is type-checked only through the sites' generated
// tsconfig, never the company's root one (Node, no DOM).

/** Where `writeApi` writes, under a company's root. */
export const API_FILE = join(".sanoma", "api.ts");

const API_NAME_PROBLEM = "A site calls this workflow api.";

/** `describeConfig`'s problem on a workflow whose api name is taken: `taken` says by what. */
export const apiNameProblem = (api: string, taken: string) => `${API_NAME_PROBLEM}${api}, ${taken}: rename it`;

type Schema = Record<string, unknown>;

/**
 * `.sanoma/api.ts` for a description: one record type per collection, and `CompanyApi` (not `Api`,
 * which inside `declare module "sanoma/site"` is the module's own), one member per
 * workflow (`apiNameOf`), per vendor of the operations a person may call directly (`OpEntry.direct`,
 * by resource) and `data` for the collections, each with its JSDoc; then `Register`'s
 * augmentation. Pure: the same description gives the same text. A workflow whose api name another
 * has, `describeConfig`'s problem on its entry, is left out, and its problem is in `problems`.
 */
export function generateApi(description: ConfigDescription): { source: string; problems: string[] } {
  const problems: string[] = [];
  const members: string[] = [];
  for (const wf of description.workflows) {
    const taken = wf.problems.filter((p) => p.message.startsWith(API_NAME_PROBLEM));
    if (taken.length) problems.push(...taken.map((p) => problemLine({ file: wf.file, ...p })));
    else members.push(workflowMember(wf));
  }
  // The ops are sorted by id, so by vendor and then resource.
  const direct = description.ops.filter((op) => op.direct && op.vendor !== DATA_VENDOR);
  for (const [vendor, ops] of Map.groupBy(direct, (op) => op.vendor)) {
    const title = description.vendors[vendor]?.title ?? vendor;
    const resources = [...Map.groupBy(ops, (op) => op.resource)].map(([resource, own]) =>
      member(undefined, resource, block(own.map(opMember))),
    );
    members.push(member(`${title}: the operations a person may call directly.`, vendor, block(resources)));
  }
  if (description.collections.length) {
    const data = description.collections.map((c) =>
      member(collectionDoc(c), c.name, `CollectionApi<${recordName(c)}>`),
    );
    members.push(member("The company's collections.", DATA_VENDOR, block(data)));
  }
  const source = [
    "// Generated by sanoma from sanoma.config.ts and the connectors it names; do not edit.",
    "// The types of `api` from sanoma/site: what a site may call, as the person on the page.",
    'import type { CollectionApi, OpFn, WorkflowFn } from "sanoma/site";',
    ...description.collections.map(
      (c) => `\n${jsdoc(`A record of ${c.title ?? c.name}.`)}type ${recordName(c)} = ${typeOf(c.record)};`,
    ),
    "",
    `interface CompanyApi ${block(members)}`,
    "",
    'declare module "sanoma/site" {',
    "  interface Register {",
    "    api: CompanyApi;",
    "  }",
    "}",
    "",
    "export {};",
    "",
  ].join("\n");
  return { source, problems };
}

/**
 * Writes `<root>/.sanoma/api.ts` (`generateApi`) when its text differs from the file's, so an
 * editor or a dev server sees no change when there is none; `wrote` says whether it did.
 */
export async function writeApi(
  root: string,
  description: ConfigDescription,
): Promise<{ wrote: boolean; file: string }> {
  const file = join(root, API_FILE);
  return { wrote: await writeChanged(file, generateApi(description).source), file };
}

/**
 * The generated files, each written when its text changed: `.sanoma/api.ts` (`writeApi`) and the
 * Cedar schema's text, `.sanoma/schema.cedarschema` (`schemaText` of `schemaOf`). `wrote` lists
 * those written, relative to the root.
 */
export async function writeGenerated(
  root: string,
  description: ConfigDescription,
  schema: CedarSchemaJson,
): Promise<{ wrote: string[] }> {
  const [api, cedar] = await Promise.all([
    writeApi(root, description),
    writeChanged(join(root, SCHEMA_FILE), schemaText(schema)),
  ]);
  return { wrote: [...(api.wrote ? [API_FILE] : []), ...(cedar ? [SCHEMA_FILE] : [])] };
}

/** Writes `text` to `file` unless the file holds it already; true when it wrote. */
async function writeChanged(file: string, text: string): Promise<boolean> {
  if ((await readFile(file, "utf8").catch(() => undefined)) === text) return false;
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, text);
  return true;
}

const workflowMember = (wf: WorkflowEntry) =>
  member(
    `${wf.title ?? wf.name}: the workflow \`${wf.name}\`${wf.builtin ? ", built in" : ""}.`,
    apiNameOf(wf.name),
    `WorkflowFn<${typeOf(wf.input)}, unknown>`,
  );

const opMember = (op: OpEntry) =>
  member(
    `${op.description ? `${op.description}\n\n` : ""}\`${op.id}\`, a ${op.effect}.`,
    op.name,
    `OpFn<${typeOf(op.input)}, unknown>`,
  );

const collectionDoc = (c: CollectionEntry) =>
  `${c.title ?? c.name}: the collection \`${c.name}\`, keyed by \`${c.key}\`.`;

/** A collection's record type's name: `outbound` gives `OutboundRecord`, never `CompanyApi` nor an imported type's. */
const recordName = (c: CollectionEntry) => `${c.name[0]!.toUpperCase()}${c.name.slice(1)}Record`;

/**
 * A JSON Schema as a TypeScript type, for the kinds a start form draws (`fieldsOf` in the app):
 * strings (a date-time among them), numbers, integers, booleans, enums and constants, objects and
 * arrays, each property with its description, and unions of those, `null` among them (a
 * collection's date, a date or a date-time; a nullable field); anything else is `unknown`.
 */
const typeOf = (schema: unknown): string => union(alternatives(schema));

/** One type of several: `unknown` when any is. */
function union(types: string[]): string {
  const distinct = new Set(types);
  return distinct.has("unknown") ? "unknown" : [...distinct].join(" | ");
}

/** The types a schema allows, one per alternative. */
function alternatives(schema: unknown): string[] {
  if (!isObject(schema)) return ["unknown"];
  if ("const" in schema && !isObject(schema.const) && !Array.isArray(schema.const)) {
    return [JSON.stringify(schema.const)];
  }
  if (Array.isArray(schema.enum) && schema.enum.length && schema.enum.every((v) => v === null || !isObject(v))) {
    return schema.enum.map((v) => JSON.stringify(v));
  }
  if (Array.isArray(schema.anyOf) && schema.anyOf.length) return schema.anyOf.flatMap(alternatives);
  if (Array.isArray(schema.type) && schema.type.length) {
    return schema.type.flatMap((type) => alternatives({ ...schema, type }));
  }
  switch (schema.type) {
    case "string":
      return ["string"];
    case "number":
    case "integer":
      return ["number"];
    case "boolean":
      return ["boolean"];
    case "null":
      return ["null"];
    case "array": {
      const item = typeOf(schema.items);
      return [new Set(alternatives(schema.items)).size > 1 && item !== "unknown" ? `(${item})[]` : `${item}[]`];
    }
    case "object":
      return [isObject(schema.properties) ? objectType(schema) : "Record<string, unknown>"];
    default:
      return ["unknown"];
  }
}

function objectType(schema: Schema): string {
  const required = new Set(Array.isArray(schema.required) ? schema.required : []);
  const lines = Object.entries(schema.properties as Schema).map(([name, prop]) => {
    const doc = isObject(prop) && typeof prop.description === "string" ? jsdoc(prop.description) : "";
    return `${doc}${key(name)}${required.has(name) ? "" : "?"}: ${typeOf(prop)};`;
  });
  // An object that takes other keys too.
  if (schema.additionalProperties !== undefined && schema.additionalProperties !== false) {
    lines.push("[key: string]: unknown;");
  }
  return block(lines);
}

/** A property's name, quoted when it is not an identifier. */
const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

/** A member, under its JSDoc when there is one. */
const member = (doc: string | undefined, name: string, type: string) =>
  `${doc ? jsdoc(doc) : ""}${key(name)}: ${type};`;

/** `{ … }` around lines, each indented a level (a nested block's lines with it); `{}` for none. */
const block = (lines: string[]) =>
  lines.length ? `{\n${lines.map((l) => l.replace(/^(?=.)/gm, "  ")).join("\n")}\n}` : "{}";

/** A JSDoc comment and the line break after it; `*\/` in the text cannot end it. */
function jsdoc(text: string): string {
  const lines = text.replaceAll("*/", "*\\/").split("\n");
  return lines.length === 1
    ? `/** ${lines[0]} */\n`
    : `/**\n${lines.map((l) => ` *${l ? ` ${l}` : ""}`).join("\n")}\n */\n`;
}
